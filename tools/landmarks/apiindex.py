"""Write API.md: every public function of the landmark kits with its signature and first doc line.

python3 apiindex.py          rewrite API.md
python3 apiindex.py --check  exit 1 if API.md is out of date (the kits changed since it was written)

Read API.md instead of the kit sources: it is about 15x smaller than archkit.py + townkit.py + landkit.py + ...
"""
import ast, hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
KITS = ["canvas.py", "archkit.py", "townkit.py", "landkit.py", "interiors.py", "finish.py", "underkit.py", "sabaody_kit.py",
        "mcb/kit.py", "mcb/bridge.py", "mcb/hulls.py", "mcb/nature.py", "mcb/lotpack.py", "mcb/shipstamp.py",
        "mcb/holy_kit.py", "mcb/impel_kit.py", "mcb/kit_interiors.py"]
OUT = os.path.join(HERE, "API.md")


def source_hash(files):
    h = hashlib.sha1()
    for f in files: h.update(open(os.path.join(HERE, f), "rb").read())
    return h.hexdigest()[:12]


def index(files):
    out = []
    for f in files:
        out.append(f"\n## {f}")
        for n in ast.parse(open(os.path.join(HERE, f)).read()).body:
            if isinstance(n, ast.FunctionDef): ms, pre = [n], ""
            elif isinstance(n, ast.ClassDef): ms, pre = [m for m in n.body if isinstance(m, ast.FunctionDef)], n.name + "."
            else: continue
            for m in ms:
                if m.name.startswith("_") and m.name != "__init__": continue
                doc = (ast.get_docstring(m) or "").split("\n")[0][:80]
                args = ast.unparse(m.args).replace("self, ", "").replace("self", "")
                out.append(f"- `{pre}{m.name}({args})`" + (f"  {doc}" if doc else ""))
    return out


def main():
    files = [f for f in KITS if os.path.exists(os.path.join(HERE, f))]
    k = source_hash(files)
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and f"sources {k}" in open(OUT).readline()
        print("API.md is current" if ok else "API.md is stale: run python3 apiindex.py")
        sys.exit(0 if ok else 1)
    head = [f"# Landmark kit API (generated by apiindex.py, sources {k}; do not edit by hand)", "",
            "Signatures and first doc lines only. To see one function: `grep -n \"def name\" file.py`, then `sed -n` that range."]
    open(OUT, "w").write("\n".join(head + index(files)) + "\n")
    print(f"wrote API.md ({os.path.getsize(OUT)} bytes) from {len(files)} kits")


if __name__ == "__main__":
    main()
