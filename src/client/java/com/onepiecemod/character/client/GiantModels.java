	/** Texture size of each giant's skin. */
	private static int size(String id) {
		return switch (id) {
			case "big_mom" -> 256;
			default -> 128;
		};
	}

	/** Parts whose normal box is not drawn (their extra boxes are): a reshaped body, e.g. Brook's thin limbs. */
	public static Set<String> stripped(String id) {
		return switch (id) {
			case "aokiji" -> Set.of("right_leg", "left_leg");
			case "big_mom" -> Set.of("head", "hat");
			case "brook" -> Set.of("body", "right_arm", "left_arm", "right_leg", "left_leg");
			case "chopper" -> Set.of("head", "hat", "body", "right_arm", "left_arm", "right_leg", "left_leg");
			case "doflamingo" -> Set.of("right_leg", "left_leg");
			case "franky" -> Set.of("right_arm", "left_arm");
			case "hancock" -> Set.of("body", "right_arm", "left_arm", "right_leg", "left_leg");
			case "imu" -> Set.of("right_leg", "left_leg");
			case "ivankov" -> Set.of("head", "hat");
			case "katakuri" -> Set.of("right_leg", "left_leg");
			case "kizaru" -> Set.of("right_leg", "left_leg");
			case "moria" -> Set.of("head", "hat", "body", "right_arm", "left_arm", "right_leg", "left_leg");
			case "vegapunk" -> Set.of("head", "hat");
			default -> Set.of();
		};
	}

	/** How far the arms and legs swing (1 = normal). Short limbs hanging far below the joint swing less. */
	public static float swing(String id) {
		return switch (id) {
			case "chopper" -> 0.4F;
			default -> 1.0F;
		};
	}

	/** Extra leg length in px (long-legged characters): GiantModel raises everything above the hips this much. */
	public static float legs(String id) {
		return switch (id) {
			case "aokiji" -> 4F;
			case "doflamingo" -> 4F;
			case "hancock" -> 5F;
			case "katakuri" -> 4F;
			case "kizaru" -> 3F;
			default -> 0.0F;
		};
	}

	/** How many px further out the shoulders sit (very wide bodies), so the arms and held items clear the body. */
	public static float armsOut(String id) {
		return switch (id) {
			case "big_mom" -> 8F;
			default -> 0.0F;
		};
	}

	/** Body parts this character does not have (Shanks has no left arm). GiantModel keeps them hidden. */
	public static Set<String> hidden(String id) {
		return switch (id) {
			case "shanks" -> Set.of("left_arm");
			default -> Set.of();
		};
	}

